// Generates THIRD_PARTY_LICENSES.md from the actual dependency graphs and
// fails when a dependency's license is not on the allowlist.
//   node scripts/licenses.mjs           # write the file + check
//   node scripts/licenses.mjs --check   # check only
import { execFileSync } from "node:child_process"
import { writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const ALLOWED = new Set([
  "MIT", "MIT-0", "Apache-2.0", "BSD-2-Clause", "BSD-3-Clause", "ISC", "0BSD",
  "Zlib", "Unicode-3.0", "Unicode-DFS-2016", "CC0-1.0", "BSL-1.0", "Unlicense",
  "MPL-2.0", "CDLA-Permissive-2.0", "BlueOak-1.0.0", "Python-2.0", "OFL-1.1",
])

/** True when an SPDX expression is satisfiable with allowed licenses. */
function allowed(expr) {
  if (!expr) return false
  const cleaned = expr.replace(/[()]/g, " ").trim()
  // OR: any alternative fully allowed. AND/WITH: all parts allowed.
  return cleaned.split(/\s+OR\s+|\s*\/\s*/).some((alt) =>
    alt.split(/\s+AND\s+/).every((part) => ALLOWED.has(part.replace(/\s+WITH\s+.*$/, "").trim()))
  )
}

const run = (cmd, args, cwd = root) =>
  execFileSync(cmd, args, { cwd, encoding: "utf8", maxBuffer: 1 << 28, shell: process.platform === "win32" })

// ── npm (production dependencies of the shipped renderer + core) ──
const npm = JSON.parse(run("pnpm", ["licenses", "list", "--prod", "--json", "--filter", "@vidra/desktop", "--filter", "@vidra/core"]))
const npmRows = []
for (const [license, pkgs] of Object.entries(npm))
  for (const p of pkgs) for (const version of p.versions ?? [p.version]) npmRows.push({ name: p.name, version, license, url: p.homepage ?? "" })
npmRows.sort((a, b) => a.name.localeCompare(b.name))

// ── Rust (normal dependencies of vidra-studio, resolved graph) ──
const meta = JSON.parse(
  run("cargo", ["metadata", "--format-version", "1", "--manifest-path", "apps/desktop/src-tauri/Cargo.toml", "--filter-platform", "x86_64-pc-windows-msvc"])
)
const byId = new Map(meta.packages.map((p) => [p.id, p]))
const nodes = new Map(meta.resolve.nodes.map((n) => [n.id, n]))
const rootId = meta.resolve.root
const seen = new Set()
const stack = [rootId]
while (stack.length) {
  const id = stack.pop()
  if (seen.has(id)) continue
  seen.add(id)
  for (const dep of nodes.get(id)?.deps ?? [])
    if (dep.dep_kinds.some((k) => k.kind === null)) stack.push(dep.pkg) // normal deps only
}
seen.delete(rootId)
const rustRows = [...seen]
  .map((id) => byId.get(id))
  .map((p) => ({ name: p.name, version: p.version, license: p.license ?? (p.license_file ? `file:${p.license_file}` : "UNKNOWN"), url: p.repository ?? "" }))
  .sort((a, b) => a.name.localeCompare(b.name))

const violations = [...npmRows, ...rustRows].filter((r) => !allowed(r.license))
const table = (rows) =>
  ["| Package | Version | License |", "| --- | --- | --- |", ...rows.map((r) => `| ${r.url ? `[${r.name}](${r.url})` : r.name} | ${r.version} | ${r.license} |`)].join("\n")

const doc = `# Third-party licenses

Generated by \`node scripts/licenses.mjs\` from the resolved dependency graphs
(npm production dependencies of the shipped renderer, and normal Rust
dependencies of the desktop app for x86_64-pc-windows-msvc). Development-only
tools (test runners, linters, build tooling) are not distributed and are not
listed.

Each package is distributed under its own license. Full license texts are
included in the respective package sources and in the installed application's
bundle where required.

## Fonts, icons and media

- **Icons:** [Lucide](https://lucide.dev) (ISC). Bundled in the renderer.
- **Fonts:** the system UI font stack only (no font files are bundled).
- **Logo and app icons:** original Vidra Studio artwork (\`branding/\`), MIT with the project.
- **UI primitives:** generated with the shadcn/ui CLI (MIT) into \`apps/desktop/src/components/ui\`.
- **Starter scaffold:** \`create-tauri-app\` (MIT OR Apache-2.0).
- **Screenshots and demo video:** captured from Vidra Studio itself with a local
  mock provider; the media shown is generated test footage (an animated
  circle), not AI output and not third-party content.
- **No provider logos** are included.

## npm packages (${npmRows.length})

${table(npmRows)}

## Rust crates (${rustRows.length})

${table(rustRows)}
`

if (!process.argv.includes("--check")) writeFileSync(join(root, "THIRD_PARTY_LICENSES.md"), doc)
if (violations.length) {
  console.error("License check FAILED for:\n" + violations.map((v) => `  ${v.name}@${v.version}: ${v.license}`).join("\n"))
  process.exit(1)
}
console.log(`License check passed: ${npmRows.length} npm packages, ${rustRows.length} Rust crates.`)
